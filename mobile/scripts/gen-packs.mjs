// Regenerates src/data/packs/index.ts from the chapter pack files present (t4-b1.ts … t5-b10.ts).
// Run: node scripts/gen-packs.mjs
import { readdirSync, writeFileSync } from 'node:fs';
const dir = new URL('../src/data/packs/', import.meta.url);
const files = readdirSync(dir)
  .filter((f) => /^t[45]-b\d+\.ts$/.test(f))
  .sort((a, b) => {
    const [, fa, ba] = a.match(/t(\d)-b(\d+)/);
    const [, fb, bb] = b.match(/t(\d)-b(\d+)/);
    return fa - fb || ba - bb;
  });
const names = files.map((f) => f.replace('.ts', '').replace('-', ''));
const out = `// AUTO-GENERATED by scripts/gen-packs.mjs — do not edit by hand.
import type { ChapterPack } from './pack';
${files.map((f, i) => `import ${names[i]} from './${f.replace('.ts', '')}';`).join('\n')}

/** All chapter packs, in syllabus order. */
export const packs: ChapterPack[] = [${names.join(', ')}];
`;
writeFileSync(new URL('index.ts', dir), out);
console.log(`packs: ${names.join(', ')}`);

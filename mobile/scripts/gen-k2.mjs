// Regenerates src/data/k2/sets/index.ts from the files in src/data/k2/sets (text-format Kertas 2 sets).
import { readdirSync, writeFileSync } from 'node:fs';
const dir = new URL('../src/data/k2/sets/', import.meta.url);
const files = readdirSync(dir).filter((f) => /^k2-(t4|penuh)-\d\d\.ts$/.test(f)).sort();
const name = (f) => f.replace('.ts', '').replace(/-(\w)/g, (_, c) => c.toUpperCase());
const out = `// AUTO-GENERATED by scripts/gen-k2.mjs. Do not edit.
${files.map((f) => `import ${name(f)} from './${f.replace('.ts', '')}';`).join('\n')}

export const k2Texts: string[] = [${files.map(name).join(', ')}];
`;
writeFileSync(new URL('index.ts', dir), out);
console.log('k2 text sets:', files.map((f) => f.replace('.ts', '')).join(', '));

// Regenerates src/data/papers/sets/index.ts from the text-format Kertas 1 papers in src/data/papers/sets.
import { readdirSync, writeFileSync } from 'node:fs';
const dir = new URL('../src/data/papers/sets/', import.meta.url);
const files = readdirSync(dir).filter((f) => /^k1-(t4|penuh)-\d\d\.ts$/.test(f)).sort();
const name = (f) => f.replace('.ts', '').replace(/-(\w)/g, (_, c) => c.toUpperCase());
const out = `// AUTO-GENERATED by scripts/gen-k1.mjs. Do not edit.
${files.map((f) => `import ${name(f)} from './${f.replace('.ts', '')}';`).join('\n')}

export const k1Texts: string[] = [${files.map(name).join(', ')}];
`;
writeFileSync(new URL('index.ts', dir), out);
console.log('k1 text sets:', files.map((f) => f.replace('.ts', '')).join(', '));
